def _keyword_detect_mode(world_setting: str) -> str:
    """根据世界观设定做关键词匹配,粗判模式 A/B/C(作为 LLM 判别的 fallback,不够准确)。"""
    text = world_setting.lower()
    for kw in _DND_KEYWORDS:
        if kw.lower() in text:
            return "C"
    for kw in _RPG_KEYWORDS:
        if kw.lower() in text:
            return "B"
    return "A"


def _parse_mode_prefix(text: str):
    """解析 [rpg|dnd|跑团|数值|trpg] 显式前缀。返回 (mode, cleaned_text)。"""
    s = text.strip()
    m = re.match(
        r"^\s*(rpg|dnd|跑团|数值|trpg|团)\s*[:：\s]\s*(.+)$",
        s,
        re.IGNORECASE | re.DOTALL,
    )
    if m:
        kw = m.group(1).lower()
        rest = m.group(2).strip()
        if kw in ("dnd", "跑团", "trpg", "团"):
            return "C", rest
        return "B", rest
    return None, s
